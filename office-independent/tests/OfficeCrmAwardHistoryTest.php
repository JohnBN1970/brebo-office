INSERT INTO office_crm_relations VALUES(1,'person','active'),(2,'organization','active');
INSERT INTO office_crm_opportunities VALUES(1,1,'won','closed'),(2,1,'won','closed'),(3,2,'won','closed')");
$r=new OfficeCrmAwardRecorder($db);
$db->beginTransaction();$r->record(1,7);$db->rollBack();
if((int)$db->query('SELECT COUNT(*) FROM office_crm_award_events')->fetchColumn()!==0)throw new RuntimeException('Award rollback failed');
if((int)$db->query('SELECT COUNT(*) FROM office_crm_relation_roles')->fetchColumn()!==0)throw new RuntimeException('Role rollback failed');
$db->beginTransaction();$r->record(1,7);$r->record(1,8);$r->record(2,7);$r->record(3,7);$db->commit();
if((int)$db->query('SELECT COUNT(*) FROM office_crm_award_events')->fetchColumn()!==3)throw new RuntimeException('Duplicate award');
if((int)$db->query('SELECT actor_id FROM office_crm_award_events WHERE opportunity_id=1')->fetchColumn()!==7)throw new RuntimeException('Original actor changed');
if((int)$db->query('SELECT COUNT(*) FROM office_crm_relation_roles')->fetchColumn()!==2)throw new RuntimeException('Customer role count');
$db->exec("UPDATE office_crm_award_events SET awarded_at='2025-01-01' WHERE opportunity_id=1");
$year=(int)gmdate('Y');
$before=OfficeCrmCustomerAcquisitionReport::forYear($db,$year);
if($year>2025 && $before!==['first_recorded_awards'=>['b2b'=>1,'b2c'=>0,'unknown'=>0],'unrecorded_won_deals'=>0,'complete_for_known_won_deals'=>true])throw new RuntimeException('Repeat customer counted');
$db->exec("UPDATE office_crm_relations SET status='archived' WHERE id=1");
if(OfficeCrmCustomerAcquisitionReport::forYear($db,$year)!==$before)throw new RuntimeException('Archive changed acquisition');
$db->exec("INSERT INTO office_crm_opportunities VALUES(4,2,'won','closed')");
if(OfficeCrmCustomerAcquisitionReport::forYear($db,$year)['complete_for_known_won_deals'])throw new RuntimeException('Missing history concealed');
