setDateField(invoiceDate,'2026-11-07');setDateField(paymentDays,'14');assert.equal(dueDate.value,'2026-11-21');assert.equal(dueDate.readOnly,true);
assert.equal(body.rows.length, 1);
set(body.rows[0], 'description', 'Opname');set(body.rows[0], 'quantity', '1,125');set(body.rows[0], 'price', '100,00');
