'use strict';
const fs = require('node:fs');
const assert = require('node:assert/strict');
const {JSDOM, VirtualConsole} = require(process.env.SALES_JSDOM_MODULE);
const console = new VirtualConsole();
console.on('jsdomError', error => { throw error; });
const dom = new JSDOM(fs.readFileSync(process.argv[2], 'utf8'), {runScripts: 'dangerously', virtualConsole: console});
const document = dom.window.document;
const body = document.getElementById('sales-lines');
const field = (row, suffix) => row.querySelector('[name$="[' + suffix + ']"]');
const set = (row, suffix, value) => { const input = field(row, suffix);input.value=value;input.dispatchEvent(new dom.window.Event('input', {bubbles:true})); };
assert.equal(body.rows.length, 1);
set(body.rows[0], 'description', 'Opname');set(body.rows[0], 'quantity', '1,125');set(body.rows[0], 'price', '100,00');
assert.equal(document.getElementById('sales-gross').textContent, '€ 136,13');
document.getElementById('sales-add-line').click();
assert.equal(body.rows.length, 2);assert.equal(field(body.rows[0], 'description').value, 'Opname');
set(body.rows[1], 'description', 'Tweede regel');set(body.rows[1], 'quantity', '2');set(body.rows[1], 'price', '10');set(body.rows[1], 'vat', '9');
assert.equal(document.getElementById('sales-gross').textContent, '€ 157,93');
body.rows[0].querySelector('[data-remove-line]').click();
assert.equal(body.rows.length, 1);assert.equal(document.getElementById('sales-gross').textContent, '€ 21,80');
assert.equal(body.rows[0].querySelector('[data-remove-line]').disabled, true);
document.getElementById('sales-add-line').click();
const names = [...document.querySelectorAll('#sales-lines input, #sales-lines select')].map(x => x.name);
assert.equal(new Set(names).size, names.length);
set(body.rows[0], 'price', 'ongeldig');assert.equal(document.getElementById('sales-gross').textContent, '—');
set(body.rows[0], 'price', '9999999.99');set(body.rows[0], 'quantity', '999999.999');
assert.equal(document.getElementById('sales-gross').textContent, '—');
process.stdout.write('OFFICE_SALES_EDITOR_DOM_OK\n');
